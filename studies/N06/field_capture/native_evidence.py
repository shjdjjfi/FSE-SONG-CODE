"""Execute official native promtool on N06 fixtures and retain an auditable log.

No `promtool` executable => NOT_EXECUTED and exit code 2. Never interpret
the upstream project's successful CI run as this project's own test pass.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import shutil
import subprocess


ROOT = Path(__file__).resolve().parent.parent


def run_promtool(out: Path, executable: str = "promtool",
                 field_cases: Path | None = None) -> dict:
    candidate = shutil.which(executable)
    record = {"engine": "Prometheus", "executed_at": datetime.now(timezone.utc).isoformat(),
              "real_project_samples": False, "fixture_origin": "N06 hand-authored and synthetic",
              "engine_version": None, "exit_code": 2, "status": "NOT_EXECUTED",
              "steps": [], "stdout_sha256": None}
    out.mkdir(parents=True, exist_ok=True)
    log_parts = []
    field_meta = None
    if field_cases is not None:
        field_cases = field_cases.resolve()
        if field_cases.parent != (ROOT / "promtool").resolve():
            raise ValueError("field fixtures must be generated next to promtool/alert_rules.yml")
        meta_path = field_cases.with_name(field_cases.stem + ".evidence.json")
        field_meta = json.loads(meta_path.read_text(encoding="utf-8"))
        if hashlib.sha256(field_cases.read_bytes()).hexdigest() != field_meta["exported_fixture_sha256"]:
            raise ValueError("field native fixture hash does not match capture audit")
        if not field_meta.get("source_capture_sha256") or not field_meta.get("cluster_uid_sha256"):
            raise ValueError("field fixture lacks real capture provenance")
        record["cluster_uid_sha256"] = field_meta["cluster_uid_sha256"]
        record["source_capture_sha256"] = field_meta["source_capture_sha256"]
        record["source_incidents_sha256"] = field_meta["source_incidents_sha256"]
        record["field_fixture_sha256"] = field_meta["exported_fixture_sha256"]
    if candidate:
        commands = [([candidate, "--version"], "version"),
                    ([candidate, "check", "rules", "alert_rules.yml"], "check_rules"),
                    ([candidate, "test", "rules", "tests.yml"], "unit_tests"),
                    ([candidate, "test", "rules", "generated_owner_cases.yml"], "generated_tests")]
        if field_cases is not None:
            commands.append(([candidate, "test", "rules", field_cases.name], "real_field_case_tests"))
        record["status"] = "RUNNING"
        for command, label in commands:
            try:
                proc = subprocess.run(command, cwd=ROOT / "promtool", capture_output=True,
                                      text=True, timeout=90, check=False)
                combined = proc.stdout + "\n" + proc.stderr
                log_parts.append(f"$ {label}\n{combined}")
                record["steps"].append({"step": label, "exit_code": proc.returncode})
                if label == "version":
                    record["engine_version"] = combined.strip().splitlines()[0] if combined.strip() else None
                if proc.returncode != 0:
                    record["exit_code"] = proc.returncode
                    record["status"] = "FAILED"
                    break
            except (subprocess.TimeoutExpired, OSError) as exc:
                log_parts.append(f"$ {label}\nexception={type(exc).__name__}\n")
                record["status"] = "FAILED"
                break
        else:
            record["exit_code"] = 0
            if field_cases is None:
                record["status"] = "PASS_NATIVE_SYNTHETIC_RULE_TESTS_ONLY"
            else:
                record["status"] = "PASS_NATIVE_REAL_TRACE_TESTS__MANUAL_PROVENANCE_CHECK_REQUIRED"
                record["real_project_samples"] = True
                record["fixture_origin"] = field_meta["fixture_origin"]
    else:
        log_parts.append("No official promtool executable was found. No native test executed.\n")
    log_text = "\n".join(log_parts)
    log_path = out / "promtool_stdout.txt"
    log_path.write_text(log_text, encoding="utf-8")
    record["stdout_sha256"] = hashlib.sha256(log_text.encode("utf-8")).hexdigest()
    record["rules_sha256"] = hashlib.sha256((ROOT / "promtool/alert_rules.yml").read_bytes()).hexdigest()
    (out / "native_test_report.json").write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    return record


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "results_field/native_attempt")
    parser.add_argument("--promtool", default="promtool")
    parser.add_argument("--field-cases", type=Path,
                        help="Optional genuine-field fixture generated by export_real_cases.py")
    args = parser.parse_args()
    record = run_promtool(args.out, args.promtool, args.field_cases)
    print(json.dumps({"status": record["status"], "exit_code": record["exit_code"],
                      "report": str(args.out / "native_test_report.json")}))
    return record["exit_code"]


if __name__ == "__main__":
    raise SystemExit(main())
