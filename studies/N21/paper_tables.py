#!/usr/bin/env python3
"""Make publication-ready main-results tables from the complete raw JSONL."""
from __future__ import annotations
import json
import statistics as st
from collections import defaultdict
from pathlib import Path
from run_n21 import CASE_SPECS, HERE

ARMS=["standard","selective_path","selective_hash","guarded_hash",
      "invalidate_all","clean_all","force_all","full_cache"]
DISPLAY={"standard":"Unforced tsc -b", "selective_path":"Path manifest",
         "selective_hash":"Output SHA manifest", "guarded_hash":"Input-guarded SHA (ours)",
         "invalidate_all":"Invalidate all buildinfo", "clean_all":"Clean build",
         "force_all":"Force full solution", "full_cache":"Complete local cache hit"}

def med(values):
    return st.median(values) if values else 0

def main():
    results=HERE/"results"
    trial=[]
    for p in results.rglob("trials.jsonl"):
        trial.extend(json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip())
    core=[r for r in trial if r["seed"]==17 and r["fault"] not in ("intact","buildinfo_missing")]
    groups=defaultdict(dict)
    for r in core:
        k=(r["case"],r["project"],r["fault"])
        if r["arm"] in groups[k]:
            raise ValueError(f"Repeated measurement in main results: {k}/{r['arm']}")
        groups[k][r["arm"]]=r
    if len(groups)!=77:
        raise ValueError(f"Unexpected number of distinct injected failure settings: {len(groups)}")
    for k,x in groups.items():
        if set(x)!=set(ARMS):
            raise ValueError(f"Incomplete paired comparison: {k} lacks {set(ARMS)-set(x)}")
    stats={}
    for arm in ARMS:
        rec=[v[arm] for v in groups.values()]
        stats[arm]={"correct":sum(r["correct"] for r in rec),"total":len(rec),
            "median_rebuilt_units":med([r["compiled_source_units_proxy"] for r in rec]),
            "median_wall_seconds":med([r["repair"]["work_seconds"] for r in rec])}
    lines=["# Main N21 Paper Tables", "", "Seed 17; 77 distinct fault/project settings and 13 project units in four workspaces. "
           "Each strategy sees the **same 77 injected settings**; input changes are evaluated separately.",
           "", "| Strategy | Exact clean-oracle agreement | Median rebuilt source units (proxy) | Median measured seconds |",
           "|---|---:|---:|---:|"]
    for arm in ARMS:
        r=stats[arm]
        lines.append(f"| {DISPLAY[arm]} | {r['correct']}/{r['total']} | "
                     f"{r['median_rebuilt_units']:.1f} | {r['median_wall_seconds']:.2f} |")
    lines.extend(["", "**Interpretation.** A complete cache hit is an *available-cache* ideal comparator. "
        "The same 77 cases include deletion, content corruption, and extra-output faults, so even "
        "`--force` does not make every case correct. Source-file units are project-level proxies; "
        "times are local, shared-machine timings, not industrial CI performance.",
        "", "## Per-project repair cost (input-guarded hash vs clean)", "",
        "| Workspace / project | Source files | Emitted files | Median rebuilt units (guarded / clean) | Median saved units | Median time saved (s) |",
        "|---|---:|---:|---:|---:|---:|"])
    project_stats=[]
    metadata={c:json.loads((HERE/"runtime"/"metadata"/f"{c}.json").read_text()) for c in CASE_SPECS}
    for case in CASE_SPECS:
        for project in CASE_SPECS[case]["projects"]:
            rec=[x for (c,p,f),x in groups.items() if c==case and p==project]
            saved=[x["clean_all"]["compiled_source_units_proxy"]-
                   x["guarded_hash"]["compiled_source_units_proxy"] for x in rec]
            saved_time=[x["clean_all"]["repair"]["work_seconds"]-
                        x["guarded_hash"]["repair"]["work_seconds"] for x in rec]
            guarded_u=[x["guarded_hash"]["compiled_source_units_proxy"] for x in rec]
            clean_u=[x["clean_all"]["compiled_source_units_proxy"] for x in rec]
            record={"case":case,"project":project,"n":len(rec),
                "sources":metadata[case]["source_units"][project],
                "outputs":metadata[case]["outputs"][project],
                "guarded_units":med(guarded_u), "clean_units":med(clean_u),
                "median_saved_units":med(saved),"median_time_saved_seconds":med(saved_time)}
            project_stats.append(record)
            lines.append(f"| {case}/{project} | {record['sources']} | {record['outputs']} | "
             f"{record['guarded_units']:.0f} / {record['clean_units']:.0f} | "
             f"{record['median_saved_units']:.0f} | {record['median_time_saved_seconds']:+.2f} |")
    latex=["% Automatically generated by paper_tables.py; do not hand-edit values.",
       "% The 77 settings are clustered within 13 projects / 7 source repositories.",
       "\\begin{table}[t]", "\\centering", "\\small",
       "\\caption{Output recovery on 77 controlled fault/project settings (TypeScript 5.9.3). "
       "Exact agreement means identical paths and SHA-256 bytes to independent clean output.}",
       "\\label{tab:n21-recovery}", "\\begin{tabular}{lrrr}", "\\toprule",
       "Strategy & Exact / 77 & Src. units$^\\dagger$ & Time (s) \\\\", "\\midrule"]
    for arm in ARMS:
        v=stats[arm]
        label=DISPLAY[arm].replace("_","\\_").replace(" - ","--")
        latex.append(f"{label} & {v['correct']}/{v['total']} & {v['median_rebuilt_units']:.1f} & "
                     f"{v['median_wall_seconds']:.2f} \\\\")
    latex.extend(["\\bottomrule","\\end{tabular}",
        "\\vspace{1mm}",
        "\\footnotesize{$^\\dagger$Sum of source-file counts for projects logged as rebuilt; "
        "not CPU work. Full cache assumes an available, complete cache entry.}",
        "\\end{table}"])
    paper={"seed":17,"settings":len(groups),"by_arm":stats,"by_project":project_stats,
       "note":"Exploratory local times; no independent industrial CI or prevalence claims."}
    write=results/"paper_main_table.json"
    write.write_text(json.dumps(paper,indent=2,ensure_ascii=False),encoding="utf-8")
    (results/"PAPER_TABLES.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
    (results/"PAPER_TABLES.tex").write_text("\n".join(latex)+"\n",encoding="utf-8")
    print(f"Made paired {len(groups)}-setting tables: {write}")

if __name__=="__main__":
    main()
